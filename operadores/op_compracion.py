#Operador Mayor o igual que
print("Operador Mayor o igual que")
print(variable_1 >= 6)
print(variable_1 >= 8)

#Operador Menor Que
print("Operador Menor que")
print(variable_1 < 6)
print(variable_1 < 8)

#Operador Menor o igual que
